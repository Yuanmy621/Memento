const list = await (await fetch('http://127.0.0.1:9222/json/list')).json();
const pg = list.find(t => t.type === 'page' && t.url.includes('5180'));
const ws = new WebSocket(pg.webSocketDebuggerUrl);
let id = 0; const w = new Map();
ws.onmessage = e => { const m = JSON.parse(e.data); const r = w.get(m.id); if (r) { w.delete(m.id); r(m); } };
await new Promise(r => ws.onopen = r);
const send = (method, params = {}) => new Promise(res => { const i = ++id; w.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
await send('Page.enable');
await new Promise(r => setTimeout(r, 800));
const r = await send('Page.captureScreenshot', { format: 'png' });
const fs = await import('node:fs');
fs.writeFileSync(process.argv[2] || 'final.png', Buffer.from(r.result.data, 'base64'));
console.log('saved', (r.result.data.length * 0.75 / 1024).toFixed(0) + 'KB');
ws.close();
